/*
 * rsa_vectors.h  --  NIST PKCS#1 v2.1 RSA test vectors
 *
 * Keys and signatures taken verbatim from the PKCS #1 v2.1 test vector file
 * (pss-vect.txt), published with the PKCS #1 v2.1 draft standard.
 * Same vectors are used by the IETF / pyca cryptography library test suite.
 *
 * Keys 1 and 10 are used here (1024-bit and 2048-bit).
 * For each key the PSS-signature from Example x.1 is included so that the
 * raw RSA primitive can be verified:
 *
 *   priv_op(sig)  must equal  em   (EMSA-PSS encoded message, deterministic)
 *   pub_op(em)    must equal  sig
 *   pub_op(priv_op(sig)) == sig   (roundtrip through private then public)
 *
 * The embedded test simply uses the signature as the raw RSA input and checks
 * that the encrypt-then-decrypt roundtrip is identity:
 *   enc = pub_op(sig)
 *   dec = priv_op(enc)
 *   PASS iff dec == sig
 */

